import type { Role } from "@prisma/client";

/**
 * Definição declarativa dos tipos de conteúdo gerenciados no painel.
 * O formulário, a validação no servidor, a listagem e o histórico são
 * gerados a partir daqui — adicionar um tipo novo não exige nova tela.
 */

export type Option = { value: string; label: string };

export type FieldDef =
  | { name: string; label: string; type: "text" | "textarea" | "markdown" | "url" | "date"; required?: boolean; help?: string; max?: number }
  | { name: string; label: string; type: "number"; required?: boolean; help?: string; integer?: boolean; min?: number; max?: number }
  | { name: string; label: string; type: "boolean"; help?: string }
  | { name: string; label: string; type: "enum"; options: Option[]; required?: boolean; help?: string; nullable?: boolean }
  | { name: string; label: string; type: "list"; help?: string }
  | { name: string; label: string; type: "json"; required?: boolean; help?: string; schema?: "blocks" | "criteria" | "any" }
  | { name: string; label: string; type: "relation"; model: string; labelField: string; required?: boolean; help?: string; nullable?: boolean }
  | { name: string; label: string; type: "claimSources"; help?: string };

export type ResourceDef = {
  key: string;
  label: string;
  singular: string;
  group: string;
  model: string;
  /** Campo identificador (padrão "id"). */
  idField?: string;
  titleField: string;
  listFields: string[];
  searchFields: string[];
  orderBy: Record<string, "asc" | "desc">[];
  editorial: boolean;
  /** Quem pode criar/editar. Padrão: todos os papéis. */
  editRoles?: Role[];
  fields: FieldDef[];
  publicPath?: (r: Record<string, unknown>) => string | null;
};


